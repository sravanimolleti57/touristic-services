/**
 * Filter hotels strictly by destinationId (primary relationship).
 */
export function getHotelsByDestinationId(destId) {
  if (!destId) return [];
  const targetId = String(destId).trim();
  return HOTELS_LIST.filter(h => String(h.destinationId) === targetId);
}

/**
 * Filter hotels by destinationName or ID.
 */
export function getHotelsByDestination(destIdentifier) {
  if (!destIdentifier) return [];
  const target = String(destIdentifier).toLowerCase().trim();

  // Try matching destinationId first
  const byId = HOTELS_LIST.filter(h => String(h.destinationId) === target);
  if (byId.length > 0) return byId;

  // Otherwise match destinationName or destination
  return HOTELS_LIST.filter(h => {
    const dName = (h.destinationName || "").toLowerCase();
    const dLoc = (h.location || "").toLowerCase();
    return dName.includes(target) || target.includes(dName) || dLoc.includes(target) || target.includes(dLoc);
  });
}

